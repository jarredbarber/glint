// Generates src/spa/export-css.ts by inlining the same stylesheet set the standalone
// `glint-md render` uses (src/renderer/head.ts), so the SPA "Download HTML" export
// matches the live render (#146). Fonts are omitted: the export CSP is `font-src data:`,
// so the CSS `url()` faces would be blocked anyway (same fallback as the portable
// renderer); math and text fall back to system/serif glyphs. Committed and regenerated
// on build so `npm test` (which runs on source, not the bundle) sees it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Cascade order: color scheme defines the :root palette vars layout.css reads.
const files = [
    'assets/color-schemes/default.css',
    'assets/layout.css',
    'assets/highlight.css',
    'assets/katex/katex.min.css',
];

const css = files.map((f) => readFileSync(join(root, f), 'utf8')).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-export-css.mjs. Do not edit by hand.
// Regenerated on \`npm run build\`; mirrors src/renderer/head.ts's stylesheet set (#146).
export const EXPORT_CSS = ${JSON.stringify(css)};
`;
writeFileSync(join(root, 'src/spa/export-css.ts'), out);
console.log(`export-css.ts: inlined ${files.length} stylesheets, ${css.length} bytes`);
