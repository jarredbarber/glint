// Generates src/spa/export-css.ts by inlining the same stylesheet set the standalone
// `glint-md render` uses (src/renderer/head.ts), so the SPA "Download HTML" export
// matches the live render (#146). KaTeX's woff2 faces are embedded as data: URIs so
// math renders in real KaTeX Computer Modern even in a self-contained export (#150);
// the export CSP is `font-src data:`, which permits data URIs but blocks the original
// same-origin `url(fonts/*)` refs. Body/heading fonts are left external (lower impact).
// Committed and regenerated on build so `npm test` (which runs on source, not the
// bundle) sees it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Inline KaTeX's woff2 faces as data: URIs and drop the woff/ttf fallbacks (woff2 is
// universal in modern browsers; keeping all three would triple the payload). Each
// @font-face src is `url(fonts/X.woff2) format("woff2"),url(...woff),url(...ttf)`.
function inlineKatexFonts(css) {
    const dir = join(root, 'assets/katex/fonts');
    return css
        .replace(/url\(fonts\/([A-Za-z0-9_-]+\.woff2)\)/g, (_, name) => {
            const b64 = readFileSync(join(dir, name)).toString('base64');
            return `url(data:font/woff2;base64,${b64})`;
        })
        .replace(/,url\(fonts\/[A-Za-z0-9_-]+\.(?:woff|ttf)\) format\("(?:woff|truetype)"\)/g, '');
}

// Cascade order: color scheme defines the :root palette vars layout.css reads.
const files = [
    'assets/color-schemes/default.css',
    'assets/layout.css',
    'assets/highlight.css',
    'assets/katex/katex.min.css',
];

const css = files
    .map((f) => {
        const raw = readFileSync(join(root, f), 'utf8');
        return f.endsWith('katex.min.css') ? inlineKatexFonts(raw) : raw;
    })
    .join('\n');
const out = `// AUTO-GENERATED by scripts/gen-export-css.mjs. Do not edit by hand.
// Regenerated on \`npm run build\`; mirrors src/renderer/head.ts's stylesheet set (#146).
export const EXPORT_CSS = ${JSON.stringify(css)};
`;
writeFileSync(join(root, 'src/spa/export-css.ts'), out);
console.log(`export-css.ts: inlined ${files.length} stylesheets, ${css.length} bytes`);
